        <h2>Cancellations, Returns &amp; Refunds FAQ</h2>
        <p>Last Updated: 13th February 2026</p>

        <h3>Section A: Cancellations</h3>

        <h4>1. Can I cancel my BillMintMall order after placing it?</h4>
        <p>
            Yes, you can cancel your order any time before it is dispatched. Once the status changes to "Dispatched" or
            "Out for Delivery," the order cannot be cancelled through the platform. In such cases, you may choose to
            reject the package at the time of delivery.
        </p>

        <h4>2. Are there any items that cannot be cancelled?</h4>
        <p>
            Express/Instant Delivery: Orders placed under "Same-Day" delivery or rapid fulfilment windows are
            non-cancellable once confirmed. Limited Window Items: Certain high-demand launches may have a restricted
            cancellation window (e.g., 30 minutes).
        </p>

        <h4>3. How do I cancel my order?</h4>
        <p>
            Visit the 'My Orders' section in your account → Select the Order → Click 'Cancel Order'. If the cancellation
            window has closed, this button will be disabled.
        </p>

        <h3>Section B: Returns &amp; Exchanges</h3>

        <h4>4. What is the return policy for BillMintMall products?</h4>
        <p>
            Returns are valid for all products purchased on the Platform, EXCEPT for those specifically marked on the
            website/product page as 'Non-Returnable.'
        </p>

        <h4>5. Which items are non-returnable and non-refundable?</h4>
        <p>
            In line with hygiene and safety standards, the following categories are typically non-returnable: Innerwear
            &amp; Intimates (Vests, Briefs, Trunks, Lingerie, Swimwear, Socks, and Hosiery); Personalized Products (any
            item customized or tailored specifically to your requirements); Final Sale Items (products explicitly marked
            as "Non-Returnable" at the time of purchase); and Hygiene-Sensitive Items (items where the hygiene seal or
            original protective packaging has been tampered with).
        </p>
        <p>
            IMPORTANT: For these specific products, a return cannot be initiated, and no refund shall be processed unless
            the item delivered was physically damaged, defective, or a completely different product from what was
            ordered.
        </p>

        <h4>6. What is the standard return window?</h4>
        <p>
            For all eligible returnable products, the window is 10 days from the date of delivery.
        </p>

        <h4>7. What are the conditions for a successful return?</h4>
        <p>
            At the time of pickup, the product must pass a quality check. Unused &amp; Unwashed: tags must be attached and
            the item must be in original condition. Complete: all original packaging (boxes/dust bags), accessories, and
            freebies must be returned. Footwear: must be tried on clean, carpeted surfaces only — scuffed soles will
            result in a rejected return.
        </p>

        <h3>Section C: Refunds</h3>

        <h4>8. How and when will I receive my refund?</h4>
        <p>
            Prepaid Orders: Refunds are credited to the original payment source (UPI/Card/Bank) within 5–7 business days
            after the item reaches our warehouse and passes quality inspection. Store Credit: You may opt for immediate
            refund into your BillMintMall Wallet/Store Credit, which can be used for future purchases.
        </p>

        <h4>9. Will my shipping charges be refunded?</h4>
        <p>
            Shipping or convenience fees are non-refundable for "Change of Mind" returns. However, if the return is due
            to a defect or error on our part, the full transaction amount (including shipping) will be refunded.
        </p>

        <h3>Section D: Damaged or Wrong Items</h3>

        <h4>10. What if I receive a damaged or wrong product?</h4>
        <p>
            Report the discrepancy within 48 hours of delivery through our Help Centre. We recommend recording an
            "Unboxing Video" for faster resolution. If verified, we will arrange an immediate replacement or full refund
            at no extra cost to you.
        </p>

