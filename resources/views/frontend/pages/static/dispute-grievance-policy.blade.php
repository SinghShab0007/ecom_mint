        <h2>Dispute &amp; Grievance Policy</h2>
        <p>Last Updated: 13th February 2026</p>

        <p>
            Welcome to BillMintMall (https://www.billmintmall.com). This Dispute Resolution Policy explains how disputes
            related to orders placed through our marketplace are handled. By using our platform, you agree to the terms
            of this policy.
        </p>

        <h4>1. Scope</h4>
        <p>
            This policy applies to disputes arising from: product not received; damaged or defective products; incorrect
            or incomplete orders; refund-related issues; return and replacement requests; payment-related concerns; and
            seller and buyer disagreements regarding an order.
        </p>

        <h4>2. Reporting a Dispute</h4>
        <p>
            Customers must report any dispute through the BillMintMall support team within the applicable return or
            complaint period mentioned for the product. To raise a dispute, customers should provide the Order ID,
            product details, a description of the issue, and supporting photographs or videos (if applicable). Failure to
            provide sufficient information may delay the resolution process.
        </p>

        <h4>3. Investigation Process</h4>
        <p>
            Upon receiving a dispute, BillMintMall will review the complaint and supporting documents. The seller may be
            contacted for clarification or additional information. Delivery records, shipment details, and other relevant
            information may be verified. If required, the logistics partner may also be involved during the
            investigation.
        </p>

        <h4>4. Resolution Timeline</h4>
        <p>
            Initial acknowledgement: within 2 business days. Investigation period: up to 7 business days. Complex
            disputes may require additional time, and customers will be informed accordingly.
        </p>

        <h4>5. Resolution Outcomes</h4>
        <p>
            After investigation, one of the following actions may be taken: full refund; partial refund; product
            replacement; return approval; or rejection of the dispute where evidence does not support the claim. The
            decision will be based on the available evidence and applicable marketplace policies.
        </p>

        <h4>6. Refund Process</h4>
        <p>
            Where a refund is approved, refunds will be initiated through the original payment method. Processing time
            may vary depending on the customer's bank or payment provider. Shipping charges may be refunded only where
            applicable.
        </p>

        <h4>7. Seller Responsibilities</h4>
        <p>
            Sellers using the BillMintMall marketplace must deliver products matching the listing description, respond
            promptly to dispute-related queries, cooperate during investigations, and accept valid returns, refunds, or
            replacements in accordance with marketplace policies. Failure to comply may result in suspension or
            termination of seller privileges.
        </p>

        <h4>8. Customer Responsibilities</h4>
        <p>
            Customers are expected to provide accurate information while placing orders, inspect products promptly upon
            delivery, report issues within the specified timelines, and provide truthful information and supporting
            evidence. Fraudulent or abusive claims may result in rejection of disputes and suspension of marketplace
            access.
        </p>

        <h4>9. Final Decision</h4>
        <p>
            BillMintMall reserves the right to make the final decision after reviewing all relevant facts, documents, and
            evidence submitted by both parties. Our decision shall be binding for disputes handled through the
            marketplace.
        </p>

