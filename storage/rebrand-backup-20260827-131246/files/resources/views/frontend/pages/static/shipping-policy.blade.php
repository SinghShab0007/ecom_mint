        <h2>Shipping Policy</h2>
        <p>Last Updated: 13th February 2026</p>

        <h4>1. Overview</h4>
        <p>
            POROSKART operates as a multi-vendor e-commerce aggregator connecting manufacturers, wholesalers, resellers,
            and customers across India. This Shipping Policy explains how orders are processed, shipped, delivered, and
            tracked after purchase.
        </p>

        <h4>2. Order Processing</h4>
        <p>
            Orders are processed after successful order placement and confirmation. Sellers receive automated order
            notifications through the POROSKART platform. Orders are prepared for dispatch only after product
            availability is confirmed by the seller. Processing Time: typically 24–72 business hours, excluding Sundays
            and public holidays.
        </p>

        <h4>3. Shipping Coverage</h4>
        <p>
            POROSKART currently ships across India through verified logistics partners. Shipping availability may vary
            depending on product category, seller location, and delivery PIN code serviceability.
        </p>

        <h4>4. Logistics Partners</h4>
        <p>
            Shipping is managed through trusted national logistics providers. B2C &amp; B2B2C Orders are assigned to
            integrated courier partners, while Bulk / B2B Orders are handled via specialized freight and surface
            logistics partners. Logistics partner allocation is automated to ensure efficient delivery.
        </p>

        <h4>5. Shipping Charges</h4>
        <p>
            Shipping charges may vary based on order value, product weight/volume, delivery location, and seller shipping
            terms. Applicable shipping fees (if any) are displayed during checkout before payment confirmation.
        </p>

        <h4>6. Order Dispatch</h4>
        <p>
            Once shipped, a Tracking ID is generated and customers receive tracking details via email, SMS, and their
            account dashboard. Shipment status can be monitored in real time.
        </p>

        <h4>7. Estimated Delivery Timelines</h4>
        <p>
            Standard Retail Orders: 3–7 business days. E-Commerce Aggregator / Reseller Orders: 4–10 business days. Bulk /
            B2B Shipments: 5–12 business days. Delivery timelines are estimates and may vary due to remote locations,
            weather conditions, logistics delays, or regulatory restrictions.
        </p>

        <h4>8. Delivery Confirmation</h4>
        <p>
            Orders are considered delivered when the shipment reaches the provided delivery address and delivery
            acknowledgment or proof of delivery is recorded by the logistics partner. Customers are requested to inspect
            packages at the time of delivery.
        </p>

        <h4>9. Failed Delivery Attempts</h4>
        <p>
            Delivery may fail if the customer is unavailable, an incorrect address is provided, or the contact number is
            unreachable. Courier partners may attempt re-delivery. Persistent failures may result in order cancellation
            or return to origin.
        </p>

        <h4>10. Shipping Delays</h4>
        <p>
            POROSKART shall not be liable for delays caused by natural disasters, government restrictions, strikes or
            operational disruptions, or unforeseen logistics issues. Customers will be notified of significant delays
            whenever possible.
        </p>

        <h4>11. Damaged or Tampered Packages</h4>
        <p>
            If you receive damaged packaging or an open or tampered parcel, please either refuse delivery, or record
            proof at delivery and contact support within 24 hours.
        </p>

        <h4>12. Returns &amp; Reverse Shipping</h4>
        <p>
            If eligible under the Return Policy, return pickup will be arranged through authorized logistics partners.
            Reverse shipping timelines depend on pickup location and product category. Detailed conditions are covered
            under our Cancellations, Returns &amp; Refunds Policy.
        </p>

        <h4>13. Address Accuracy</h4>
        <p>
            Customers are responsible for providing a correct shipping address, valid contact details, and proper
            recipient availability. POROSKART is not responsible for delays arising from incorrect information.
        </p>

